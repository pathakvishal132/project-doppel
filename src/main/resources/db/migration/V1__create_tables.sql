-- Brand registry
CREATE TABLE brand (
    id   BIGINT       PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE brand_token (
    brand_id BIGINT      NOT NULL REFERENCES brand (id),
    token    VARCHAR(64) NOT NULL,
    PRIMARY KEY (brand_id, token)
);

CREATE TABLE brand_vpa (
    brand_id BIGINT       NOT NULL REFERENCES brand (id),
    vpa      VARCHAR(255) NOT NULL UNIQUE,
    PRIMARY KEY (brand_id, vpa)
);

-- Every screening request (idempotent on request_id). Full account number is never stored.
CREATE TABLE screening (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id         VARCHAR(64)  NOT NULL,
    vpa                VARCHAR(255) NOT NULL,
    display_name       VARCHAR(100) NOT NULL,
    masked_account     VARCHAR(18)  NOT NULL,
    registrant_ref     VARCHAR(64)  NOT NULL,
    matched_brand_id   BIGINT REFERENCES brand (id),
    matched_brand_name VARCHAR(100),
    decision           VARCHAR(10)  NOT NULL,
    score              INT          NOT NULL,
    reasons            TEXT         NOT NULL,
    request_timestamp  TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_screening_request_id UNIQUE (request_id)
);

-- Alerts: only REVIEW and BLOCK screenings
CREATE TABLE alert (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id     VARCHAR(64)  NOT NULL,
    vpa            VARCHAR(255) NOT NULL,
    display_name   VARCHAR(100) NOT NULL,
    brand_id       BIGINT REFERENCES brand (id),
    brand_name     VARCHAR(100),
    decision       VARCHAR(10)  NOT NULL,
    score          INT          NOT NULL,
    reasons        TEXT         NOT NULL,
    masked_account VARCHAR(18)  NOT NULL,
    registrant_ref VARCHAR(64)  NOT NULL,
    status         VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_alert_request_id UNIQUE (request_id)
);

CREATE INDEX idx_alert_status_created ON alert (status, created_at);
CREATE INDEX idx_alert_brand ON alert (brand_id);
