-- Task 3: analyst disposition on alerts + audit trail
ALTER TABLE alert ADD COLUMN disposition VARCHAR(30);
ALTER TABLE alert ADD COLUMN updated_at TIMESTAMP WITH TIME ZONE;
ALTER TABLE alert ADD COLUMN version BIGINT DEFAULT 0 NOT NULL;

CREATE TABLE alert_audit_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id        BIGINT       NOT NULL REFERENCES alert (id),
    action          VARCHAR(40)  NOT NULL,
    previous_status VARCHAR(20),
    new_status      VARCHAR(20)  NOT NULL,
    analyst         VARCHAR(100) NOT NULL,
    comment         VARCHAR(1000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_audit_alert ON alert_audit_event (alert_id, created_at);

